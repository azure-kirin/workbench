/**
 * Writes `sets.css` and `sets.json` from `sets.ts`.
 *
 *   node --experimental-strip-types sandbox/palette-lab/generate.ts
 *
 * sets.css has two parts:
 *   1. `[data-set]` — every declaration on globals.css's :root that reads
 *      another token through var(). A custom property resolves its var()s
 *      where it is DECLARED, so `--surface: var(--ink-900)` computed on :root
 *      would never see a wrapper's new --ink-900. Re-declaring the semantic
 *      and component layers on the wrapper makes real components follow the
 *      set. The wash's accent slots are re-aimed at the aura trio.
 *   2. One rule per set with its primitives (OKLCH, hex in a comment).
 */
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { formatOklch, oklchToRgb, rgbToHex } from "./color.ts";
import { readDeclarations } from "./contrast.ts";
import { type PaletteSet, SETS, WASH_FROM_AURA } from "./sets.ts";

const here = import.meta.dirname;
const declared = readDeclarations(
  readFileSync(resolve(here, "../../src/globals.css"), "utf8"),
);

const declare = (entries: [string, string][]) =>
  entries.map(([name, value]) => `  ${name}: ${value};`).join("\n");

const shared = declare([
  ...[...declared].filter(
    ([name, value]) => value.includes("var(") && !(name in WASH_FROM_AURA),
  ),
  ...Object.entries(WASH_FROM_AURA),
]);

const hex = (set: PaletteSet, token: string) =>
  rgbToHex(oklchToRgb(set.primitives[token] as PaletteSet["primitives"][string]));

function block(set: PaletteSet): string {
  const lines: string[] = [];
  const section = (title: string, tokens: string[]) => {
    lines.push(`  /* ${title} */`);
    for (const token of tokens) {
      const colour = set.primitives[token];
      if (colour)
        lines.push(`  ${token}: ${formatOklch(colour)}; /* ${hex(set, token)} */`);
    }
  };
  section(
    `${set.neutralName} → --ink-*`,
    set.ramps.neutral.map((s) => s.token),
  );
  section(
    `Button accent · ${set.accentName} → --copper-*`,
    set.ramps.accent.map((s) => s.token),
  );
  section(
    "Success → --moss-*",
    set.ramps.success.map((s) => s.token),
  );
  section(
    "Warning → --ochre-*",
    set.ramps.warning.map((s) => s.token),
  );
  section(
    "Danger → --brick-*",
    set.ramps.danger.map((s) => s.token),
  );
  section(
    "Info → --slate-*",
    set.ramps.info.map((s) => s.token),
  );
  section(
    `Aura · ${set.aura.map((a) => a.name).join(", ")}`,
    set.aura.map((a) => a.token),
  );
  section(
    `Identity — ${set.identity.map((h) => `${h.n} ${h.name}`).join(", ")}`,
    set.identity.flatMap((h) => [h.solid, h.text]),
  );
  lines.push("  /* Scrim — the darkest neutral at 70% */");
  lines.push(
    `  --scrim-70: ${formatOklch(set.scrim.colour, set.scrim.alpha)}; /* ${hex(set, "--ink-950")}b3 */`,
  );
  return [
    `/* ${set.name} — ${set.idea} */`,
    `:root[data-set="${set.id}"],`,
    `[data-set="${set.id}"] {`,
    ...lines,
    "}",
  ].join("\n");
}

const css = [
  "/* GENERATED by generate.ts from sets.ts — do not edit by hand. */",
  "",
  "/* The semantic and component layers of globals.css, re-declared so they",
  "   resolve against the set on any [data-set] element; the Ambient Wash's",
  "   accent slots read the set's aura trio. */",
  "[data-set] {",
  shared,
  "}",
  "",
  ...SETS.map(block).flatMap((b) => [b, ""]),
].join("\n");
writeFileSync(resolve(here, "sets.css"), css);

const colourJson = (set: PaletteSet, token: string) => ({
  token,
  hex: hex(set, token),
  oklch: formatOklch(set.primitives[token] as PaletteSet["primitives"][string]),
});

const json = SETS.map((set) => ({
  id: set.id,
  name: set.name,
  idea: set.idea,
  trio: set.trioName,
  accent: { name: set.accentName, slot: set.accentSlot },
  greys: set.neutralName,
  aura: set.aura.map((a) => ({
    slot: a.slot,
    name: a.name,
    ...colourJson(set, a.token),
    anchor: a.anchor,
  })),
  ramps: Object.fromEntries(
    Object.entries(set.ramps).map(([role, steps]) => [
      role,
      steps.map(({ token, step }) => ({ step, ...colourJson(set, token) })),
    ]),
  ),
  identity: set.identity.map((h) => ({
    n: h.n,
    name: h.name,
    solid: colourJson(set, h.solid),
    text: colourJson(set, h.text),
  })),
}));
writeFileSync(resolve(here, "sets.json"), `${JSON.stringify(json, null, 2)}\n`);

execFileSync(
  resolve(here, "../../node_modules/.bin/biome"),
  ["format", "--write", "--vcs-use-ignore-file=false", "sets.css", "sets.json"],
  { cwd: here, stdio: "ignore" },
);
console.log(`Wrote sets.css and sets.json for ${SETS.length} sets.`);
